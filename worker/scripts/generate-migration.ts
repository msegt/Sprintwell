// Regenerates worker/migrations/0001_initial.sql from the Kysely migrations used
// by the Node server, so SQLite (Node), PostgreSQL and D1 share one schema.
// Run: npx tsx worker/scripts/generate-migration.ts
import { writeFileSync } from 'node:fs';
import BetterSqlite3 from 'better-sqlite3';
import { openDatabase } from '../../server/src/db';

// Build the schema in a temporary SQLite file with the Kysely migrator, then read it back.
const path = new URL('../migrations/.tmp-schema.db', import.meta.url).pathname;
const h2 = await openDatabase(path);
await h2.close();
const db = new BetterSqlite3(path);
const rows = db
  .prepare("select type, name, sql from sqlite_master where sql is not null and name not like 'kysely_%' and name not like 'sqlite_%' order by case type when 'table' then 0 else 1 end, rowid")
  .all() as { sql: string }[];
db.close();
const out = ['-- Generated by worker/scripts/generate-migration.ts from server/src/db/migrations.ts. Do not edit by hand.', ...rows.map((r) => `${r.sql};`), ''].join('\n');
writeFileSync(new URL('../migrations/0001_initial.sql', import.meta.url).pathname, out);
const { rmSync } = await import('node:fs');
rmSync(path, { force: true });
for (const ext of ['-wal', '-shm']) rmSync(path + ext, { force: true });
console.log(`Wrote ${rows.length} statements`);
