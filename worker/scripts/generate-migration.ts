// Writes one Cloudflare D1 migration file per Kysely migration in
// server/src/db/migrations.ts, so SQLite (Node), PostgreSQL and D1 share one schema.
// Existing files are never rewritten: shipped migrations must not change.
// Run: npx tsx worker/scripts/generate-migration.ts
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import BetterSqlite3 from 'better-sqlite3';
import { Kysely, SqliteDialect, type CompiledQuery } from 'kysely';
import { Migrator } from 'kysely/migration';
import { migrations } from '../../server/src/db/migrations';

const dir = new URL('../migrations/', import.meta.url).pathname;
const existing = new Set(readdirSync(dir).filter((f) => f.endsWith('.sql')));

let captured: CompiledQuery[] = [];
const db = new Kysely<any>({
  dialect: new SqliteDialect({ database: new BetterSqlite3(':memory:') }),
  log(event) {
    if (event.level === 'query') captured.push(event.query);
  },
});
const migrator = new Migrator({ db, provider: { getMigrations: async () => migrations } });

/** Inlines bound parameters (D1 migration files are plain SQL). */
function inline(q: CompiledQuery): string {
  let i = 0;
  return q.sql.replace(/\?/g, () => {
    const v = q.parameters[i++];
    if (typeof v === 'number') return String(v);
    if (v === null || v === undefined) return 'null';
    return `'${String(v).replace(/'/g, "''")}'`;
  });
}

let written = 0;
const names = Object.keys(migrations).sort();
for (const [index, name] of names.entries()) {
  captured = [];
  const { error } = await migrator.migrateTo(name);
  if (error) throw error;
  const file = `${String(index + 1).padStart(4, '0')}_${name.replace(/^\d+_/, '')}.sql`;
  if (existing.has(file) || (index === 0 && existsSync(`${dir}0001_initial.sql`))) continue;
  const statements = captured
    .filter((q) => !/kysely_migration/i.test(q.sql) && !/^\s*(select|with|begin|commit|rollback|pragma)\b/i.test(q.sql))
    .map((q) => `${inline(q)};`);
  writeFileSync(`${dir}${file}`, [`-- Generated by worker/scripts/generate-migration.ts from migration ${name}. Do not edit by hand.`, ...statements, ''].join('\n'));
  console.log(`Wrote ${file} (${statements.length} statements)`);
  written++;
}
await db.destroy();
if (!written) console.log('D1 migrations are up to date.');
